#!/usr/bin/env bash
# Rebuilds extension/dist/client.js from src/theme.css (no Node needed).
set -e
cd "$(dirname "$0")"
css="$(sed -e 's/\\/\\\\/g' -e 's/`/\\`/g' -e 's/\${/\\${/g' src/theme.css)"
mkdir -p extension/dist
{
  printf '%s\n' "// Generated by build.sh from src/theme.css - do not edit by hand."
  printf '%s\n' "import { definePterodactylExtension } from '@pterodactyl/sdk';"
  printf '%s' 'const CSS = `'
  printf '%s' "$css"
  printf '%s\n' '`;'
  cat <<'JS'

// Inject the tokens as early as possible (module load), once.
(function () {
    if (typeof document === 'undefined') return;
    var id = 'orbital-theme-css';
    var el = document.getElementById(id);
    if (!el) {
        el = document.createElement('style');
        el.id = id;
        document.head.appendChild(el);
    }
    el.textContent = CSS;
})();

// A theme needs no slots, screens or components.
export default definePterodactylExtension({
    setup() {},
});
JS
} > extension/dist/client.js
echo "built extension/dist/client.js"
