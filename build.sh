#!/usr/bin/env bash
# Rebuilds extension/dist/client.js from src/*.css/js (no Node needed).
set -e
cd "$(dirname "$0")"
css="$(sed -e 's/\\/\\\\/g' -e 's/`/\\`/g' -e 's/\${/\\${/g' src/theme.css)"
mkdir -p extension/dist
{
  printf '%s\n' "// Generated by build.sh from src/ - do not edit by hand."
  printf '%s\n' "import { definePterodactylExtension } from '@pterodactyl/sdk';"
  printf '%s' 'const CSS = `'
  printf '%s' "$css"
  printf '%s\n' '`;'
  cat <<'JS'

// 1) Theme tokens, injected once at module load.
(function () {
    if (typeof document === 'undefined') return;
    var id = 'orbital-theme-css';
    var el = document.getElementById(id);
    if (!el) { el = document.createElement('style'); el.id = id; document.head.appendChild(el); }
    el.textContent = CSS;
})();

// 2) React comes from the panel's import map. If it is missing, only the
//    React features are skipped - the theme and palette keep working.
var R = null;
try { var __r = await import('react'); R = __r.default && __r.default.createElement ? __r.default : __r; } catch (e) { console.warn('[orbital] react unavailable, favourites disabled'); }

JS
  cat src/palette.js
  echo
  cat src/favourites.js
  cat <<'JS'

export default definePterodactylExtension({
    setup(ctx) {
        try {
            if (R && ctx && ctx.slots) ctx.slots.register('dashboard.serverRow.name.after', OrbitalStar);
        } catch (e) {
            console.warn('[orbital] favourites disabled:', e);
        }
    },
});
JS
} > extension/dist/client.js
echo "built extension/dist/client.js"
